package day07.practice;

public class VowelChar {

	public static void main(String[] args) {
		
		char C  = 'b';
		
		if(C == 'A'||C == 'E'||C == 'I'||C == 'O'||C == 'U'||C == 'a'||C == 'e'||C == 'i'||C == 'o'||C == 'u') {
			System.out.println(C + " is a vowel.");
		}else {
			System.out.println(C + " is a consonant.");
		}
		
		
	}
}
