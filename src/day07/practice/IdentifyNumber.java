package day07.practice;

public class IdentifyNumber {

	public static void main (String[] args) {
		int num = -18;
		
		if(num > 0) {
			System.out.println(num + " is Positive Number.");
		}else if(num < 0) {
			System.out.println(num + " is negative Number.");
		}else {
			System.out.println(num + " is Zero.");
		}
	}
}
